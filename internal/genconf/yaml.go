// commandKey is the header line that makes a generated template reproducible.
const commandKey = "# command: "

// Header is what a generated YAML says about itself.
type Header struct {
	Name    string   // the template name
	Version string   // the snif that wrote it
	Argv    []string // the full `snif gen …` argument list, as invoked
	Image   string   // the image: path to record, relative to this file
}

// YAML renders the snorg templates: section for a laid-out page.
//
// It is written as text rather than marshalled, for two reasons: the header
// comment (which is the file's regeneration recipe) must survive, and the byte
// output must be stable — regenerating an unchanged template must produce an
// identical file, so a template under version control never churns. That is also
// why no timestamp is written.
func YAML(p *layout.Page, h Header) ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "# snif template %q\n", h.Name)
	fmt.Fprintf(&b, "# generated by snif %s — re-render rather than editing by hand\n", h.Version)
	fmt.Fprintf(&b, "%s%s\n", commandKey, Quote(h.Argv))
	fmt.Fprintf(&b, "# re-render: snif gen -f %s\n", yamlName(h.Name))
	b.WriteString("#\n")
	b.WriteString("# Every widget is encoded in the id of its box (docs/widgets.md), so this\n")
	b.WriteString("# section is both snorg's template config and snif's complete form contract.\n")
	b.WriteString("# Pass it to either tool with -c.\n")
	b.WriteString("templates:\n")
	fmt.Fprintf(&b, "  - image: %s\n", h.Image)
	b.WriteString("    boxes:\n")

	for _, it := range p.Items() {
		fmt.Fprintf(&b, "      # %s %s\n", it.Kind, it.Name)
		for _, box := range it.Boxes {
			fmt.Fprintf(&b, "      - {id: %s, label: %s, rect: {x: %d, y: %d, w: %d, h: %d}, analyze: %t}\n",
				yamlStr(box.ID), yamlStr(box.Label),
				box.Rect.X, box.Rect.Y, box.Rect.W, box.Rect.H, box.Analyze)
		}
	}
	return []byte(b.String()), nil
}

// Name returns a template's conventional file basenames. The image name is only a
// convention — snif recognizes a template by the widgets in its box ids, never by
// a filename — but a consistent one keeps an archive's templates/ folder readable.
func Name(name string) (image, yaml string) { return "snif-" + name + ".png", yamlName(name) }

func yamlName(name string) string { return "snif-" + name + ".yaml" }

// ReadCommand returns the argument list recorded in a generated YAML's header,
// which is how `snif gen -f` reproduces a template.
func ReadCommand(data []byte) ([]string, error) {
	s := bufio.NewScanner(strings.NewReader(string(data)))
	for s.Scan() {
		line := s.Text()
		if !strings.HasPrefix(line, "#") {
			break // the header is over; a hand-written config has no command
		}
		if rest, ok := strings.CutPrefix(line, commandKey); ok {
			argv, err := Split(rest)
			if err != nil {
				return nil, fmt.Errorf("header command: %w", err)
			}
			if len(argv) >= 2 && argv[0] == "snif" && argv[1] == "gen" {
				argv = argv[2:]
			}
			return argv, nil
		}
	}
	return nil, fmt.Errorf("no %q line: this file was not written by snif gen", strings.TrimSpace(commandKey))
}

// yamlStr quotes a scalar so ids holding ':' and labels holding anything stay
// unambiguous in the flow mappings above.
func yamlStr(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

// Quote renders an argument list as a shell command line that Split reads back.
func Quote(argv []string) string {
	parts := make([]string, 0, len(argv)+2)
	parts = append(parts, "snif", "gen")
	for _, a := range argv {
		parts = append(parts, shellQuote(a))
	}
	return strings.Join(parts, " ")
}

func shellQuote(s string) string {
	if s != "" && !strings.ContainsAny(s, " \t\n'\"\\$`*?[]{}()<>|&;#!~") {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// Split reads a shell-quoted command line back into arguments. It handles the
// quoting Quote produces — single quotes, double quotes and backslash escapes —
// and rejects an unterminated quote rather than guessing.
func Split(line string) ([]string, error) {
	var out []string
	var cur strings.Builder
	started := false
	quote := byte(0)

	for i := 0; i < len(line); i++ {
		c := line[i]
		switch {
		case quote == '\'':
			if c == '\'' {
				quote = 0
				continue
			}
			cur.WriteByte(c)
		case quote == '"':
			if c == '\\' && i+1 < len(line) && (line[i+1] == '"' || line[i+1] == '\\') {
				i++
				cur.WriteByte(line[i])
				continue
			}
			if c == '"' {
				quote = 0
				continue
			}
			cur.WriteByte(c)
		case c == '\'' || c == '"':
			quote = c
			started = true
		case c == '\\' && i+1 < len(line):
			i++
			cur.WriteByte(line[i])
			started = true
		case c == ' ' || c == '\t':
			if started {
				out = append(out, cur.String())
				cur.Reset()
				started = false
			}
		default:
			cur.WriteByte(c)
			started = true
		}
	}
	if quote != 0 {
		return nil, fmt.Errorf("unterminated %c quote", quote)
	}
	if started {
		out = append(out, cur.String())
	}
	return out, nil
}

// BoxCount is the number of template boxes a page produces — the figure a `gen`
// run reports, since it is what a reader of the YAML sees.
func BoxCount(p *layout.Page) int {
	n := 0
	for _, it := range p.Items() {
		n += len(it.Boxes)
	}
	return n
}

// Kinds summarizes a page's widgets and regions for a one-line report.
func Kinds(p *layout.Page) string {
	counts := map[spec.Kind]int{}
	var order []spec.Kind
	for _, it := range p.Items() {
		if counts[it.Kind] == 0 {
			order = append(order, it.Kind)
		}
		counts[it.Kind]++
	}
	var parts []string
	for _, k := range order {
		parts = append(parts, fmt.Sprintf("%d %s", counts[k], k))
	}
	return strings.Join(parts, ", ")
}
